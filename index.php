<?php
declare(strict_types=1);
ini_set('session.use_strict_mode', '1'); // reject session IDs that were not generated by the server
ini_set('session.cookie_httponly', '1'); // make the cookie inaccessible to JavaScript to protect against XXS attacks
ini_set('session.cookie_samesite', 'Lax'); // limit CSRF attacks by restricting third-party cookies.
session_start();
$sessionLifetime = 1800; // 30 minutes
if (isset($_SESSION['last_activity']) && (time() - $_SESSION['last_activity'] >
$sessionLifetime)) {
$_SESSION = [];
session_destroy();
session_start();
}
$_SESSION['last_activity'] = time();
// HTTP security headers
header('X-Frame-Options: DENY'); // anti clickjacking
header('X-Content-Type-Options: nosniff'); // prevents MIME-sniffing
header('Referrer-Policy: strict-origin-when-cross-origin');
header("Content-Security-Policy: default-src 'self'; style-src 'self' 'unsafe-inline'"); // limits XSS
require_once __DIR__ . '/controllers/AuthController.php';
$authController = new AuthController();
$action = $_GET['action'] ?? 'home';
switch ($action) {
    // ---------------- REGISTER ----------------
case 'register':
if (AuthController::isAuthenticated()) {
header('Location: index.php?action=dashboard');
exit;
}
$errors = [];
$old = [];
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
$errors = $authController->register($_POST);
$old = ['username' => $_POST['username'] ?? '', 'email' => $_POST['email'] ??
''];
if (empty($errors)) {
header('Location: index.php?action=login&registered=1');
exit;
}
}
$csrfToken = $authController->getCsrfToken();
require __DIR__ . '/views/register.php'; // case 'register' (same idea in case 'login')
break;
/*require __DIR__ . '/views/register.php'; // case 'register' (same idea in case 'login')
break;*/

// ---------------- LOGIN ----------------
case 'login':
if (AuthController::isAuthenticated()) {
header('Location: index.php?action=dashboard');
exit;
}
$errors = [];
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
$errors = $authController->login($_POST);
if (empty($errors)) {
    if (AuthController::hasPendingTwoFactor()) {
        header('Location: index.php?action=verify2fa');
        exit;
    }
    $redirect = ($_SESSION['role'] ?? '') === 'admin' ? 'admin' : 'dashboard';
    header('Location: index.php?action=' . $redirect);
    exit;
}
}
$csrfToken = $authController->getCsrfToken();
/*require __DIR__ . '/views/register.php'; // case 'register' (same idea in case 'login')
break;*/
require __DIR__ . '/views/login.php';
break;
// ---------------- LOGOUT ----------------
case 'logout':
$authController->logout();
header('Location: index.php?action=login');
exit;

// ---------------- USER SPACE (role: user - frontoffice) ----------------
case 'dashboard':
AuthController::requireAuth();
$user = $authController->findById((int) $_SESSION['user_id']);
if (!$user || !$user->isActive()) {
$authController->logout();
header('Location: index.php?action=login');
exit;
}
require __DIR__ . '/views/user_space.php';
break;

// ---------------- ADMIN SPACE (role: admin only - backoffice) ----------------
case 'admin':
AuthController::requireRole('admin');
$user = $authController->findById((int) $_SESSION['user_id']);
$allUsers = $authController->getAllUsers();
$totalUsers = $authController->countAllUsers();
$totalAdmins = $authController->countByRole('admin');
$totalRegular = $authController->countByRole('user');
require __DIR__ . '/views/admin_space.php';
break;

// ---------------- HOME ----------------
case 'home':
if (AuthController::isAuthenticated()) {
header('Location: index.php?action=' . (($_SESSION['role'] ?? '') ===
'admin' ? 'admin' : 'dashboard'));
} else {
header('Location: index.php?action=login');
}
exit;

// ---------------- DEACTIVATE ACCOUNT ----------------
case 'deactivate':
    AuthController::requireAuth();
    $errors = [];
    if ($_SERVER['REQUEST_METHOD'] === 'POST') {
        $errors = $authController->deactivateAccount((int) $_SESSION['user_id'], $_POST);
        if (empty($errors)) {
            $authController->logout();
            header('Location: index.php?action=login&deactivated=1');
            exit;
        }
    }
    $csrfToken = $authController->getCsrfToken();
    require __DIR__ . '/views/desactivate.php';
    break;

// ---------------- 2FA: SECOND LOGIN STEP ----------------
case 'verify2fa':
    if (AuthController::isAuthenticated()) {
        header('Location: index.php?action=dashboard');
        exit;
    }
    if (!AuthController::hasPendingTwoFactor()) {
        header('Location: index.php?action=login');
        exit;
    }
    $errors = [];
    if ($_SERVER['REQUEST_METHOD'] === 'POST') {
        $errors = $authController->verifyTwoFactorLogin($_POST);
        if (empty($errors)) {
            $redirect = ($_SESSION['role'] ?? '') === 'admin' ? 'admin' : 'dashboard';
            header('Location: index.php?action=' . $redirect);
            exit;
        }
        if (!AuthController::hasPendingTwoFactor()) { // expired or too many attempts
            header('Location: index.php?action=login');
            exit;
        }
    }
    $csrfToken = $authController->getCsrfToken();
    require __DIR__ . '/views/verify2fa.php';
    break;

// ---------------- 2FA: ENABLE / DISABLE ----------------
case '2fa':
    AuthController::requireAuth();
    $user = $authController->findById((int) $_SESSION['user_id']);
    if (!$user) {
        $authController->logout();
        header('Location: index.php?action=login');
        exit;
    }
    $errors = [];
    if ($_SERVER['REQUEST_METHOD'] === 'POST') {
        $errors = (($_POST['do'] ?? '') === 'disable')
            ? $authController->disableTwoFactor($user->getId(), $_POST)
            : $authController->enableTwoFactor($user->getId(), $_POST);
        if (empty($errors)) {
            header('Location: index.php?action=2fa&done=1');
            exit;
        }
    }
    $csrfToken = $authController->getCsrfToken();
    $secret  = $user->isTwoFactorEnabled() ? null : $authController->getSetupSecret();
    $otpauth = $secret ? $authController->getOtpauthUri($user, $secret) : null;
    require __DIR__ . '/views/twofactor.php';
    break;


// ---------------- FORGOT PASSWORD ----------------
case 'forgot':
    if (AuthController::isAuthenticated()) {
        header('Location: index.php?action=dashboard');
        exit;
    }
    $errors = [];
    $sent = false;
    if ($_SERVER['REQUEST_METHOD'] === 'POST') {
        $errors = $authController->requestPasswordReset($_POST);
        $sent = empty($errors);
    }
    $csrfToken = $authController->getCsrfToken();
    require __DIR__ . '/views/forgot.php';
    break;

// ---------------- RESET PASSWORD ----------------
case 'reset':
    if (AuthController::isAuthenticated()) {
        header('Location: index.php?action=dashboard');
        exit;
    }
    $errors = [];
    $token = (string) ($_GET['token'] ?? $_POST['token'] ?? '');
    if ($_SERVER['REQUEST_METHOD'] === 'POST') {
        $errors = $authController->resetPassword($token, $_POST);
        if (empty($errors)) {
            header('Location: index.php?action=login&reset=1');
            exit;
        }
    }
    $validToken = $authController->validateResetToken($token) !== null;
    $csrfToken = $authController->getCsrfToken();
    require __DIR__ . '/views/reset.php';
    break;

default:
http_response_code(404);
echo '404 - Page not found';
break;
}