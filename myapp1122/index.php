<?php
declare(strict_types=1);

// 1. Secure session configuration (ini_set BEFORE session_start)
ini_set('session.use_strict_mode', '1');   // reject session IDs not generated by the server
ini_set('session.cookie_httponly', '1');   // cookie invisible to JavaScript (XSS)
ini_set('session.cookie_samesite', 'Lax'); // limits CSRF
// ini_set('session.cookie_secure', '1');  // uncomment when served over HTTPS
session_start();

// 2. Session expiration after 30 minutes of inactivity
$sessionLifetime = 1800;
if (isset($_SESSION['last_activity']) && (time() - $_SESSION['last_activity'] > $sessionLifetime)) {
    $_SESSION = [];
    session_destroy();
    session_start();
}
$_SESSION['last_activity'] = time();

// 3. HTTP security headers
header('X-Frame-Options: DENY');
header('X-Content-Type-Options: nosniff');
header('Referrer-Policy: strict-origin-when-cross-origin');
header("Content-Security-Policy: default-src 'self'; style-src 'self' 'unsafe-inline'");

// 4. Dependencies
require_once __DIR__ . '/controllers/AuthController.php';

$authController = new MyApp1122AuthController();
$providers = $authController->getProviders();
$authController->loginFromCookie(); // "remember me": silent re-login

// 5. Routing
$action = is_string($_GET['action'] ?? null) ? $_GET['action'] : 'home';

switch ($action) {

    // ---------------- HOME ----------------
    case 'home':
        header('Location: ' . (MyApp1122AuthController::isAuthenticated() ? MyApp1122AuthController::homeUrl() : 'index.php?action=login'));
        exit;

    // ---------------- REGISTER ----------------
    case 'register':
        if (MyApp1122AuthController::isAuthenticated()) {
            header('Location: ' . MyApp1122AuthController::homeUrl());
            exit;
        }
        $errors = [];
        $old = [];
        if ($_SERVER['REQUEST_METHOD'] === 'POST') {
            $errors = $authController->register($_POST);
            $old = ['username' => $_POST['username'] ?? '', 'email' => $_POST['email'] ?? ''];
            if (empty($errors)) {
                header('Location: index.php?action=login&registered=1');
                exit;
            }
        }
        $csrfToken = $authController->getCsrfToken();
        require __DIR__ . '/views/register.php';
        break;

    // ---------------- LOGIN ----------------
    case 'login':
        if (MyApp1122AuthController::isAuthenticated()) {
            header('Location: ' . MyApp1122AuthController::homeUrl());
            exit;
        }
        $errors = [];
        $old = [];
        if ($_SERVER['REQUEST_METHOD'] === 'POST') {
            $errors = $authController->login($_POST);
            $old = ['email' => $_POST['email'] ?? ''];
            if (empty($errors)) {
                header('Location: ' . MyApp1122AuthController::homeUrl());
                exit;
            }
        }
        $csrfToken = $authController->getCsrfToken();
        require __DIR__ . '/views/login.php';
        break;

    // ---------------- OAUTH: start (Google / GitHub / Discord) ----------------
    case 'oauth':
        // On success this redirects to the provider and exits; we only get back here on error.
        $errors = $authController->oauthStart(is_string($_GET['provider'] ?? null) ? $_GET['provider'] : '');
        $old = [];
        $csrfToken = $authController->getCsrfToken();
        require __DIR__ . '/views/login.php';
        break;

    // ---------------- OAUTH: callback (via oauth_callback.php) ----------------
    case 'oauth_callback':
        $errors = $authController->oauthCallback($_GET);
        if (empty($errors)) {
            header('Location: ' . MyApp1122AuthController::homeUrl());
            exit;
        }
        $old = [];
        $csrfToken = $authController->getCsrfToken();
        require __DIR__ . '/views/login.php';
        break;

    // ---------------- FORGOT PASSWORD ----------------
    case 'forgot':
        if (MyApp1122AuthController::isAuthenticated()) {
            header('Location: ' . MyApp1122AuthController::homeUrl());
            exit;
        }
        $errors = [];
        $old = [];
        $sent = false;
        if ($_SERVER['REQUEST_METHOD'] === 'POST') {
            $errors = $authController->requestReset($_POST);
            $old = ['email' => $_POST['email'] ?? ''];
            $sent = empty($errors);
        }
        $csrfToken = $authController->getCsrfToken();
        require __DIR__ . '/views/forgot.php';
        break;

    // ---------------- RESET PASSWORD (link received by email) ----------------
    case 'reset':
        $token = is_string($_REQUEST['token'] ?? null) ? $_REQUEST['token'] : '';
        $errors = [];
        if ($_SERVER['REQUEST_METHOD'] === 'POST') {
            $errors = $authController->resetPassword($_POST);
            if (empty($errors)) {
                header('Location: index.php?action=login&reset=1');
                exit;
            }
        }
        $valid = $authController->isResetTokenValid($token);
        $csrfToken = $authController->getCsrfToken();
        require __DIR__ . '/views/reset.php';
        break;

    // ---------------- LOGOUT ----------------
    case 'logout':
        $authController->logout();
        header('Location: index.php?action=login');
        exit;

    // ---------------- USER SPACE (role: user - frontoffice) ----------------
    case 'dashboard':
        MyApp1122AuthController::requireAuth();
        $user = $authController->findById((int) $_SESSION['user_id']);
        if (!$user) {
            $authController->logout();
            header('Location: index.php?action=login');
            exit;
        }
        require __DIR__ . '/views/user_space.php';
        break;

    // ---------------- ADMIN SPACE (role: admin only - backoffice) ----------------
    case 'admin':
        MyApp1122AuthController::requireRole('admin');
        $user = $authController->findById((int) $_SESSION['user_id']);
        $allUsers = $authController->getAllUsers();
        $totalUsers = $authController->countAllUsers();
        $totalAdmins = $authController->countByRole('admin');
        $totalRegular = $authController->countByRole('user');
        require __DIR__ . '/views/admin_space.php';
        break;

    default:
        http_response_code(404);
        echo '404 - Page not found';
        break;
}
